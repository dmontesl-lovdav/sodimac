package com.sodimac.rebates.dto;

public class RebateProveedorDto {

	private Integer idRebateProveedor;
	private String numProveedor;
	private String nomProveedor;
	private String origen;
	private String rutv;
	private String rfc;
	private String correo;
	private String regimenFiscal;
	private String codigoPostal;

	public Integer getIdRebateProveedor() {
		return idRebateProveedor;
	}

	public void setIdRebateProveedor(Integer idRebateProveedor) {
		this.idRebateProveedor = idRebateProveedor;
	}

	public String getNumProveedor() {
		return numProveedor;
	}

	public void setNumProveedor(String numProveedor) {
		this.numProveedor = numProveedor;
	}

	public String getNomProveedor() {
		return nomProveedor;
	}

	public void setNomProveedor(String nomProveedor) {
		this.nomProveedor = nomProveedor;
	}

	public String getOrigen() {
		return origen;
	}

	public void setOrigen(String origen) {
		this.origen = origen;
	}

	public String getRutv() {
		return rutv;
	}

	public void setRutv(String rutv) {
		this.rutv = rutv;
	}

	public String getRfc() {
		return rfc;
	}

	public void setRfc(String rfc) {
		this.rfc = rfc;
	}

	public String getCorreo() {
		return correo;
	}

	public void setCorreo(String correo) {
		this.correo = correo;
	}

	public String getRegimenFiscal() {
		return regimenFiscal;
	}

	public void setRegimenFiscal(String regimenFiscal) {
		this.regimenFiscal = regimenFiscal;
	}

	public String getCodigoPostal() {
		return codigoPostal;
	}

	public void setCodigoPostal(String codigoPostal) {
		this.codigoPostal = codigoPostal;
	}

}
