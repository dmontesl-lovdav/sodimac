package com.sodimac.facturacion.models;

public class DatosControl {
	
	private String idCfdi;
	private String idStatus;
	private String estatusImpresion;
	private String estatusCorreo;
	private String estatusArchivo;
	private String idRechazo;
	private String idComplemento;

	public String getIdCfdi() {
		return idCfdi;
	}

	public void setIdCfdi(String idCfdi) {
		this.idCfdi = idCfdi;
	}

	public String getIdStatus() {
		return idStatus;
	}

	public void setIdStatus(String idStatus) {
		this.idStatus = idStatus;
	}

	public String getEstatusImpresion() {
		return estatusImpresion;
	}

	public void setEstatusImpresion(String estatusImpresion) {
		this.estatusImpresion = estatusImpresion;
	}

	public String getEstatusCorreo() {
		return estatusCorreo;
	}

	public void setEstatusCorreo(String estatusCorreo) {
		this.estatusCorreo = estatusCorreo;
	}

	public String getEstatusArchivo() {
		return estatusArchivo;
	}

	public void setEstatusArchivo(String estatusArchivo) {
		this.estatusArchivo = estatusArchivo;
	}

	public String getIdRechazo() {
		return idRechazo;
	}

	public void setIdRechazo(String idRechazo) {
		this.idRechazo = idRechazo;
	}

	public String getIdComplemento() {
		return idComplemento;
	}

	public void setIdComplemento(String idComplemento) {
		this.idComplemento = idComplemento;
	}

}
