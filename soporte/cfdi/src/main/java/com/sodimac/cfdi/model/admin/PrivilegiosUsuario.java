package com.sodimac.cfdi.model.admin;

public class PrivilegiosUsuario {

	private int idPerfil;
	private int c;
	private int r;
	private int u;
	private int d;
	private int admin;

	public int getIdrol() {
		return idPerfil;
	}

	public void setIdrol(int idrol) {
		this.idPerfil = idrol;
	}

	public int getC() {
		return c;
	}

	public void setC(int c) {
		this.c = c;
	}

	public int getR() {
		return r;
	}

	public void setR(int r) {
		this.r = r;
	}

	public int getU() {
		return u;
	}

	public void setU(int u) {
		this.u = u;
	}

	public int getD() {
		return d;
	}

	public void setD(int d) {
		this.d = d;
	}

	public int getAdmin() {
		return admin;
	}

	public void setAdmin(int admin) {
		this.admin = admin;
	}

}
